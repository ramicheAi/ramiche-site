"use client";

/* ══════════════════════════════════════════════════════════════
   Command Center — device bootstrap / approval entry
   (founder correction, CC-PRODUCTION-OWNER-RECOVERY-01 follow-up)

   middleware.ts sends any browser with NO `cc_device` cookie here instead
   of straight to Firebase sign-in. Two non-Firebase paths:
     - ?token=... (or pasted manually): the one-time bootstrap secret,
       only works while zero devices are enrolled (first device ever).
     - ?code=...  (or pasted manually): a short-lived, single-use code
       generated by an already-enrolled device (every subsequent device).
   Firebase sign-in is offered only as an explicit fallback link, never
   auto-redirected to.
   ══════════════════════════════════════════════════════════════ */

import { Suspense, useEffect, useState } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import { safeCommandCenterNext } from "@/lib/command-center-next";

export default function BootstrapPage() {
  return (
    <Suspense fallback={null}>
      <BootstrapForm />
    </Suspense>
  );
}

function BootstrapForm() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const next = safeCommandCenterNext(searchParams.get("next"));
  const urlToken = searchParams.get("token") || "";
  const urlCode = searchParams.get("code") || "";

  const [value, setValue] = useState(urlToken || urlCode || "");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [autoTried, setAutoTried] = useState(false);

  async function attempt(v: string) {
    if (!v.trim()) return;
    setError(null);
    setBusy(true);
    try {
      // Try redeem (device-approval code) first, then bootstrap (first-
      // device secret) — a code and a bootstrap secret never collide in
      // practice, and trying both means one input field covers either
      // magic link without the owner needing to know which kind it is.
      const redeemRes = await fetch("/api/command-center/auth/device/redeem", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ code: v.trim() }),
      });
      if (redeemRes.ok) {
        router.push(next);
        return;
      }

      const bootstrapRes = await fetch("/api/command-center/auth/device/bootstrap", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ token: v.trim() }),
      });
      if (bootstrapRes.ok) {
        router.push(next);
        return;
      }

      const body = await bootstrapRes.json().catch(() => ({}));
      setError(
        body.error === "already_enrolled"
          ? "This device is already enrolled, or a device already exists for this account. Use the unlock page, or get an approval code from an already-enrolled device."
          : "That code or token wasn't recognized, or has expired."
      );
    } catch {
      setError("Unexpected error.");
    } finally {
      setBusy(false);
    }
  }

  // Magic-link auto-submit: a token/code in the URL tries itself once,
  // with zero typing.
  useEffect(() => {
    if (!autoTried && (urlToken || urlCode)) {
      setAutoTried(true);
      void attempt(urlToken || urlCode);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    await attempt(value);
  }

  return (
    <div style={{ minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center", background: "#0e0e18", color: "#fff" }}>
      <form onSubmit={handleSubmit} style={{ width: 320, display: "flex", flexDirection: "column", gap: 12 }}>
        <h1 style={{ fontSize: 18, fontWeight: 600, marginBottom: 4 }}>Command Center</h1>
        <p style={{ fontSize: 13, opacity: 0.7, marginBottom: 8 }}>
          This device isn&apos;t enrolled yet. Paste your bootstrap token (first device) or a device-approval
          code (from an already-enrolled device), or open a magic link that already has one.
        </p>
        <input
          type="text"
          autoComplete="off"
          placeholder="Bootstrap token or approval code"
          value={value}
          onChange={(e) => setValue(e.target.value)}
          autoFocus
          style={{ padding: 10, borderRadius: 8, border: "1px solid #333", background: "#15151f", color: "#fff" }}
        />
        {error && <p style={{ color: "#f87171", fontSize: 13 }}>{error}</p>}
        <button
          type="submit"
          disabled={busy || !value.trim()}
          style={{ padding: 10, borderRadius: 8, border: "none", background: "#00f0ff", color: "#000", fontWeight: 600, cursor: busy ? "default" : "pointer", opacity: busy || !value.trim() ? 0.6 : 1 }}
        >
          {busy ? "Checking…" : "Continue"}
        </button>
        <a href={`/command-login?next=${encodeURIComponent(next)}`} style={{ fontSize: 12, opacity: 0.6, textAlign: "center", color: "#fff" }}>
          Or sign in with Firebase (recovery)
        </a>
      </form>
    </div>
  );
}
